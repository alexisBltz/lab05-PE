test('capturas auténticas de las interfaces y adaptación de escritorio', async ({ page, browser }) => {
  await ready(page); await shot(page, '01_inicio.png');
  await page.getByRole('button', { name: 'Nuevo movimiento', exact: true }).click();
  await page.getByLabel('Monto en soles', { exact: true }).fill('12.50');
  await page.getByLabel('Descripción', { exact: true }).fill('Almuerzo universitario');
  await shot(page, '02_registro.png');
  await page.getByRole('button', { name: 'Cerrar formulario', exact: true }).click();
  await go(page, 'Actividad'); await shot(page, '03_actividad.png');
  await go(page, 'Mi plan'); await shot(page, '04_plan.png');
  await page.getByTestId('card-Mi meta de ahorro').screenshot({ path: path.join(captures, '05_meta_ahorro.png') });
  await go(page, 'Análisis'); await shot(page, '06_analisis.png');
  await go(page, 'Aprende'); await shot(page, '07_aprende.png');
  await page.getByRole('button', { name: 'Marcar lectura 01', exact: true }).click();
  await page.reload(); await expect(page.getByText('1 de 3 lecturas marcadas')).toBeVisible();
  await shot(page, '08_persistencia.png');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: 'es-PE' });
  const desktop = await context.newPage(); await ready(desktop);
  await shot(desktop, '09_escritorio.png');
  expect(await desktop.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(1440);
  await context.close();
});
