import { test, expect, type Page } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import path from 'node:path';
const captures = path.resolve('../evidencias/capturas');
mkdirSync(captures, { recursive: true });
const go = async (p: Page, name: string) => {
  await p.getByRole('button', { name: 'Ir a ' + name, exact: true }).click();
  const titles: Record<string, string> = { 'Inicio': 'Más claridad para tu día', 'Actividad': 'Cada movimiento cuenta', 'Mi plan': 'Un plan a tu medida', 'Análisis': 'Entiende tus hábitos', 'Aprende': 'Aprende a tu ritmo' };
  await expect(p.getByTestId('screen-title')).toHaveText(titles[name]);
};
const ready = async (p: Page) => { await p.goto('/'); await expect(p.getByTestId('balance')).toHaveText('S/ 950.00'); };
const shot = async (p: Page, name: string) => { await p.evaluate(() => document.fonts.ready); await p.screenshot({ path: path.join(captures, name), animations: 'disabled' }); };

test('movimientos: validación, ingreso, edición, eliminación, gasto y persistencia', async ({ page }) => {
  await ready(page);
  await page.getByRole('button', { name: 'Nuevo movimiento', exact: true }).click();
  await page.getByLabel('Monto en soles', { exact: true }).fill('0');
  await page.getByRole('button', { name: 'Guardar movimiento', exact: true }).click();
  await expect(page.getByText('Ingresa un monto mayor a cero')).toBeVisible();
  await page.getByRole('button', { name: 'Tipo ingreso', exact: true }).click();
  await page.getByLabel('Monto en soles', { exact: true }).fill('100');
  await page.getByLabel('Descripción', { exact: true }).fill('Ingreso de prueba');
  await page.getByRole('button', { name: 'Guardar movimiento', exact: true }).click();
  await expect(page.getByTestId('balance')).toHaveText('S/ 1,050.00');
  await go(page, 'Actividad');
  await page.getByRole('button', { name: 'Editar Ingreso de prueba', exact: true }).click();
  await page.getByLabel('Monto en soles', { exact: true }).fill('120');
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click();
  await page.getByRole('button', { name: 'Editar Ingreso de prueba', exact: true }).click();
  await page.getByRole('button', { name: 'Eliminar movimiento', exact: true }).click();
  await page.getByRole('button', { name: 'Confirmar eliminación', exact: true }).click();
  await expect(page.getByText('Ingreso de prueba', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Nuevo movimiento', exact: true }).click();
  await page.getByLabel('Monto en soles', { exact: true }).fill('15');
  await page.getByLabel('Descripción', { exact: true }).fill('Gasto persistente');
  await page.getByRole('button', { name: 'Guardar movimiento', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Editar Gasto persistente' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Editar Gasto persistente' })).toBeVisible();
  await go(page, 'Inicio');
  await expect(page.getByTestId('balance')).toHaveText('S/ 935.00');
  await page.getByRole('switch', { name: 'Ocultar importes' }).click();
  await expect(page.getByTestId('balance')).toHaveText('S/ ••••');
  await page.getByRole('switch', { name: 'Ocultar importes' }).click();
  await expect(page.getByTestId('balance')).toHaveText('S/ 935.00');
});

test('presupuesto y meta: validación, guardado y cálculo diario', async ({ page }) => {
  await ready(page); await go(page, 'Mi plan');
  await page.getByLabel('Próximo ingreso AAAA-MM-DD', { exact: true }).fill('2026-02-30');
  await page.getByRole('button', { name: 'Guardar mi plan', exact: true }).click();
  await expect(page.getByText('El próximo ingreso debe tener una fecha válida desde hoy.')).toBeVisible();
  const future = new Date(); future.setDate(future.getDate() + 14);
  await page.getByLabel('Próximo ingreso AAAA-MM-DD', { exact: true }).fill(future.toLocaleDateString('en-CA'));
  await page.getByLabel('Presupuesto mensual en soles', { exact: true }).fill('600');
  await page.getByRole('button', { name: 'Guardar mi plan', exact: true }).click();
  await expect(page.getByText('Plan guardado', { exact: true })).toBeVisible();
  await page.getByLabel('Reserva en soles', { exact: true }).fill('9999');
  await page.getByRole('button', { name: 'Guardar meta de ahorro', exact: true }).click();
  await expect(page.getByText('Revisa los datos:')).toBeVisible();
  await page.getByLabel('Reserva en soles', { exact: true }).fill('150');
  await page.getByRole('button', { name: 'Guardar meta de ahorro', exact: true }).click();
  await expect(page.getByText('Meta de ahorro guardada')).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Reserva en soles', { exact: true })).toHaveValue('150');
  await expect(page.getByLabel('Presupuesto mensual en soles', { exact: true })).toHaveValue('600');
  await go(page, 'Inicio');
  await expect(page.getByTestId('daily')).toHaveText('S/ 15.33');
});

